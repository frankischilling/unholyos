%include "Kernel/KernelA.inc"

%define BOOT_HIGH_LOC_DVD ((BOOT_RAM_LIMIT-BOOT_STK_SIZE-DVD_BOOT_LOADER_SIZE)>>4)

BITS 16
ORG 0

BDVD_START:
	CLD
	MOV	AX,BOOT_HIGH_LOC_DVD
	MOV	ES,AX
	CLI
	MOV	SS,AX
	MOV	SP,BOOT_STK_SIZE+DVD_BOOT_LOADER_SIZE
	STI

	CALL	.get_rip
.get_rip:
	POP	BX
	SUB	BX,.get_rip-BDVD_START
	SHR	BX,4
	MOV	AX,CS
	ADD	AX,BX
	MOV	DS,AX
	XOR	SI,SI
	XOR	DI,DI
	MOV	CX,DVD_BOOT_LOADER_SIZE
	REP MOVSB
	MOV	AX,BOOT_HIGH_LOC_DVD
	MOV	DS,AX
	JMP	BOOT_HIGH_LOC_DVD:BDVD_MAIN

BDVD_BIOS_DRV_NUM:	DB 0
BDVD_PAGE:		DB 0

ALIGN 4,DB 0
BDVD_DAP:		DB 16,0
BDVD_DAP_COUNT:		DW 1
			DW 0
BDVD_DAP_BUF_SEG:	DW 0
BDVD_DAP_BLK:		DQ 0

BDVD_LOADING_MSG:	DB "Loading UnholyOS",0
BDVD_NOT64_MSG:		DB "UnholyOS requires a 64-bit capable processor.",13,10,0
BDVD_READ_MSG:		DB " Could not read the UnholyOS kernel.",13,10,0

; The RedSea image builder patches this extent.
	DB "UNHOLYOS-CD-LBA!"
BDVD_BLK:		DD 0
BDVD_BLK_CNT:		DW 0
BDVD_SHIFT_BLKS:	DW 0
BDVD_PROGRESS_STEP:	DD 0
BDVD_PROGRESS_VAL:	DD 0

BDVD_PUT_CHAR:
	MOV	AH,0xE
	MOV	BL,7
	MOV	BH,[BDVD_PAGE]
	INT	0x10
	RET

BDVD_PUTS:
	LODSB
	TEST	AL,AL
	JZ	.done
	CALL	BDVD_PUT_CHAR
	JMP	BDVD_PUTS
.done:
	RET

BDVD_MAIN:
	MOV	[BDVD_BIOS_DRV_NUM],DL
	MOV	AH,0xF
	INT	0x10
	MOV	[BDVD_PAGE],BH

	MOV	EAX,0x80000000
	CPUID
	CMP	EAX,0x80000001
	JB	.unsupported
	MOV	EAX,0x80000001
	CPUID
	BT	EDX,29
	JNC	.unsupported

	MOV	SI,BDVD_LOADING_MSG
	CALL	BDVD_PUTS
	MOVZX	ECX,WORD [BDVD_BLK_CNT]
	TEST	CX,CX
	JZ	.read_failed
	MOV	EAX,(80-7-9)<<16
	XOR	EDX,EDX
	DIV	ECX
	MOV	[BDVD_PROGRESS_STEP],EAX
	MOV	EAX,[BDVD_BLK]
	MOV	[BDVD_DAP_BLK],EAX
	MOV	WORD [BDVD_DAP_BUF_SEG],BOOT_RAM_BASE>>4

.read_blk:
	PUSH	CX
	MOV	WORD [BDVD_DAP_COUNT],1
	MOV	SI,BDVD_DAP
	MOV	AH,0x42
	MOV	DL,[BDVD_BIOS_DRV_NUM]
	PUSH	DS
	INT	0x13
	POP	DS
	POP	CX
	JC	.read_failed

	INC	DWORD [BDVD_DAP_BLK]
	ADD	WORD [BDVD_DAP_BUF_SEG],DVD_BLK_SIZE>>4
	MOV	BX,[BDVD_PROGRESS_VAL+2]
	MOV	EAX,[BDVD_PROGRESS_STEP]
	ADD	[BDVD_PROGRESS_VAL],EAX
	CMP	[BDVD_PROGRESS_VAL+2],BX
	JE	.next_blk
	PUSH	CX
	MOV	AL,'.'
	CALL	BDVD_PUT_CHAR
	POP	CX
.next_blk:
	LOOP	.read_blk

	; RedSea clusters are 512 bytes. Move the kernel down to BOOT_RAM_BASE.
	MOV	BX,[BDVD_SHIFT_BLKS]
	TEST	BX,BX
	JZ	.handoff
	MOV	AX,BOOT_RAM_BASE>>4
	MOV	ES,AX
	SHL	BX,5
	ADD	AX,BX
	PUSH	DS
	MOV	DS,AX
	MOV	CX,[CS:BDVD_BLK_CNT]
.shift:
	PUSH	CX
	XOR	SI,SI
	XOR	DI,DI
	MOV	CX,DVD_BLK_SIZE/4
	REP MOVSD
	MOV	AX,DS
	ADD	AX,DVD_BLK_SIZE>>4
	MOV	DS,AX
	MOV	AX,ES
	ADD	AX,DVD_BLK_SIZE>>4
	MOV	ES,AX
	POP	CX
	LOOP	.shift
	POP	DS

.handoff:
	MOV	EBX,[BDVD_BLK]
	MOVZX	EAX,WORD [BDVD_SHIFT_BLKS]
	SHL	EAX,16
	MOV	AX,BOOT_SRC_DVD
	JMP	(BOOT_RAM_BASE>>4):0

.unsupported:
	MOV	SI,BDVD_NOT64_MSG
	JMP	.stop
.read_failed:
	MOV	SI,BDVD_READ_MSG
.stop:
	CALL	BDVD_PUTS
	CLI
.halt:
	HLT
	JMP	.halt

TIMES DVD_BOOT_LOADER_SIZE-($-$$) DB 0
