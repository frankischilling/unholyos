%include "Kernel/KernelA.inc"

%define MEM_PAGE_SIZE	0x200000
%define PAGE_TABLE_SIZE	0x1000
%define PAGE_TABLE_BASE	(SYS_FIXED_AREA+SYS_FIXED_AREA_SIZE)

GLOBAL SYS_INIT_PAGE_TABLES,MEM_PML2,MEM_PML3,MEM_PML4,MEM_MAPPED_SPACE,MEM_HEAP_BASE
GLOBAL MEM_2MEG_NUM,MEM_1GIG_NUM,MEM_512GIG_NUM
GLOBAL SYS_INIT_16MEG_SYS_CODE_BP,SYS_CODE_BP,SYS_DATA_BP
EXTERN MEM_E801,MEM_PHYSICAL_SPACE,SYS_RUN_LEVEL,SYS_SERIAL_PUTS
EXTERN sys_mem_init_flag,sys_mem_init_val

SECTION .boot32 progbits alloc exec nowrite align=16
BITS 32

SYS_INIT_PAGE_TABLES:
	MOV	EAX,[MEM_PHYSICAL_SPACE]
	MOV	EDX,[MEM_PHYSICAL_SPACE+4]
	ADD	EDX,1
	JC	.no_memory
	MOV	[MEM_MAPPED_SPACE],EAX
	MOV	[MEM_MAPPED_SPACE+4],EDX

	ADD	EAX,MEM_PAGE_SIZE-1
	ADC	EDX,0
	CMP	EDX,0x200000
	JAE	.no_memory
	SHRD	EAX,EDX,21
	MOV	EBP,EAX			; 2 MiB pages.
	LEA	EBX,[EBP+511]
	SHR	EBX,9			; Page directories.
	LEA	ESI,[EBX+511]
	SHR	ESI,9			; Directory pointer tables.
	CMP	ESI,512
	JA	.no_memory
	MOV	[MEM_2MEG_NUM],EBP
	MOV	[MEM_1GIG_NUM],EBX
	MOV	[MEM_512GIG_NUM],ESI

	MOV	DWORD [MEM_PML2],PAGE_TABLE_BASE
	MOV	EDI,EBX
	SHL	EDI,12
	ADD	EDI,PAGE_TABLE_BASE
	MOV	[MEM_PML3],EDI
	MOV	EDI,ESI
	SHL	EDI,12
	ADD	EDI,[MEM_PML3]
	MOV	[MEM_PML4],EDI
	ADD	EDI,PAGE_TABLE_SIZE
	MOV	[MEM_HEAP_BASE],EDI
	MOVZX	EAX,WORD [MEM_E801]
	SHL	EAX,10
	ADD	EAX,SYS_FIXED_AREA
	CMP	EDI,EAX
	JAE	.no_memory

	MOV	ECX,EDI
	SUB	ECX,SYS_FIXED_AREA
	SHR	ECX,2
	MOV	EDI,SYS_FIXED_AREA
	XOR	EAX,EAX
	REP STOSD

	MOV	EDI,[MEM_PML2]
	MOV	ECX,EBP
	MOV	EAX,0x87
	XOR	EDX,EDX
.page:
	MOV	[EDI],EAX
	MOV	[EDI+4],EDX
	ADD	EDI,8
	ADD	EAX,MEM_PAGE_SIZE
	ADC	EDX,0
	LOOP	.page

	MOV	EDI,[MEM_PML3]
	MOV	ECX,EBX
	MOV	EAX,[MEM_PML2]
	OR	EAX,7
.directory:
	MOV	[EDI],EAX
	ADD	EDI,8
	ADD	EAX,PAGE_TABLE_SIZE
	LOOP	.directory

	MOV	EDI,[MEM_PML4]
	MOV	ECX,ESI
	MOV	EAX,[MEM_PML3]
	OR	EAX,7
.pointer:
	MOV	[EDI],EAX
	ADD	EDI,8
	ADD	EAX,PAGE_TABLE_SIZE
	LOOP	.pointer
	RET

.no_memory:
	MOV	ESI,.message
	CALL	SYS_SERIAL_PUTS
.halt:
	HLT
	JMP	.halt
.message:
	DB "UnholyOS: unable to build the initial page tables",13,10,0

SYS_INIT_16MEG_SYS_CODE_BP:
	; The fixed area was cleared by SYS_INIT_PAGE_TABLES.
	MOV	DWORD [SYS_CODE_BP],SYS_FIXED_CODE_BP
	MOV	EDI,[MEM_HEAP_BASE]
	MOVZX	EAX,WORD [MEM_E801]
	SHL	EAX,10
	ADD	EAX,SYS_FIXED_AREA
	SUB	EAX,EDI
	TEST	BYTE [sys_mem_init_flag],1
	JZ	.pool
	PUSH	EAX
	PUSH	EDI
	MOV	ECX,EAX
	MOV	AL,[sys_mem_init_val]
	REP STOSB
	POP	EDI
	POP	EAX
.pool:
	SHR	EAX,MEM_PAG_BITS

	MOV	DWORD [EDI],0
	MOV	DWORD [EDI+4],0
	MOV	DWORD [EDI+MB_SIGNATURE],MBS_UNUSED_SIGNATURE_VAL
	MOV	[EDI+MB_PAGS],EAX
	MOV	[SYS_FIXED_CODE_BP+BP_MEM_FREE_LST],EDI
	SHL	EAX,MEM_PAG_BITS
	MOV	[SYS_FIXED_CODE_BP+BP_ALLOCED_U8S],EAX
	BTS	DWORD [SYS_RUN_LEVEL],RLf_16MEG_SYS_CODE_BP
	RET

SECTION .bss
ALIGN 8
SYS_CODE_BP:		RESQ 1
SYS_DATA_BP:		RESQ 1
MEM_MAPPED_SPACE:	RESQ 1
MEM_2MEG_NUM:		RESQ 1
MEM_1GIG_NUM:		RESQ 1
MEM_512GIG_NUM:		RESQ 1
MEM_PML2:		RESD 1
MEM_PML3:		RESD 1
MEM_PML4:		RESD 1
MEM_HEAP_BASE:		RESD 1

SECTION .note.GNU-stack noalloc noexec nowrite progbits
