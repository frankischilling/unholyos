%include "Kernel/KernelA.inc"

GLOBAL SYS_FIND_PCIBIOS_SERVICE_DIR,SYS_FIND_PCI_SERVICES,FarCall32
GLOBAL SYS_PCIBIOS_SERVICE_DIR,SYS_PCI_SERVICES
EXTERN SYS_ENTER_LONG_MODE,SET_FS_BASE,SET_GS_BASE,c32

%define C32_EAX		0
%define C32_EBX		4
%define C32_ECX		8
%define C32_EDX		12
%define C32_ESI		16
%define C32_EDI		20
%define C32_EFLAGS	24

SECTION .boot32 progbits alloc exec nowrite align=16
BITS 32

SYS_FIND_PCIBIOS_SERVICE_DIR:
	MOV	ESI,0xE0000
.scan:
	CMP	DWORD [ESI],'_32_'
	JNE	.next
	MOVZX	ECX,BYTE [ESI+9]
	SHL	ECX,4
	JZ	.next
	LEA	EDX,[ESI+ECX]
	CMP	EDX,0x100000
	JA	.next

	MOV	EDI,ESI
	XOR	EAX,EAX
.checksum:
	ADD	AL,[EDI]
	INC	EDI
	LOOP	.checksum
	TEST	AL,AL
	JNZ	.next
	MOV	[SYS_PCIBIOS_SERVICE_DIR],ESI
	MOV	EAX,[ESI+4]
	MOV	[SYS_PCIBIOS_SERVICE_CALL],EAX
	RET

.next:
	ADD	ESI,4
	CMP	ESI,0xFFFF0
	JBE	.scan
	RET

SYS_FIND_PCI_SERVICES:
	CMP	DWORD [SYS_PCIBIOS_SERVICE_DIR],0
	JE	.done
	MOV	EAX,'$PCI'
	XOR	EBX,EBX
	CALL	FAR [SYS_PCIBIOS_SERVICE_CALL]
	TEST	AL,AL
	JNZ	.done
	LEA	EAX,[EBX+EDX]
	MOV	[SYS_PCI_SERVICES],EAX
.done:
	RET

SECTION .text
BITS 64

FarCall32:
	TEST	EDI,EDI
	JZ	.missing
	MOV	[REL C32_ADD],EDI
	PUSH	RBX
	PUSH	RBP
	PUSH	R12
	PUSH	R13
	PUSH	R14
	PUSH	R15
	PUSHFQ
	PUSH	QWORD [FS:0]
	PUSH	QWORD [GS:0]
	MOV	[REL C32_RSP],RSP
	PUSH	GDT_DS
	PUSH	BOOT_RAM_LIMIT
	PUSH	0
	PUSH	GDT_CS32
	LEA	RAX,[REL .compat]
	PUSH	RAX
	IRETQ
.missing:
	XOR	EAX,EAX
	RET

BITS 32
.compat:
	WBINVD
	MOV	EAX,CR0
	BTR	EAX,31
	MOV	CR0,EAX

	MOV	ECX,0xC0000080
	XOR	EDX,EDX
	XOR	EAX,EAX
	WRMSR

	MOV	AX,GDT_DS
	MOV	FS,AX
	MOV	GS,AX
	MOV	EAX,[c32+C32_EAX]
	MOV	EBX,[c32+C32_EBX]
	MOV	ECX,[c32+C32_ECX]
	MOV	EDX,[c32+C32_EDX]
	MOV	ESI,[c32+C32_ESI]
	MOV	EDI,[c32+C32_EDI]
	CALL	FAR [C32_ADD]
	PUSHFD
	POP	DWORD [c32+C32_EFLAGS]
	MOV	[c32+C32_EAX],EAX
	MOV	[c32+C32_EBX],EBX
	MOV	[c32+C32_ECX],ECX
	MOV	[c32+C32_EDX],EDX
	MOV	[c32+C32_ESI],ESI
	MOV	[c32+C32_EDI],EDI
	PUSH	DWORD 0
	CALL	SYS_ENTER_LONG_MODE

BITS 64
	MOV	RSP,[REL C32_RSP]
	POP	RAX
	CALL	SET_GS_BASE
	POP	RAX
	CALL	SET_FS_BASE
	POPFQ
	POP	R15
	POP	R14
	POP	R13
	POP	R12
	POP	RBP
	POP	RBX
	MOV	EAX,1
	RET

SECTION .data
ALIGN 4
SYS_PCIBIOS_SERVICE_CALL:
	DD	0
	DW	GDT_CS32
C32_ADD:
	DD	0
	DW	GDT_CS32

SECTION .bss
ALIGN 8
C32_RSP:
	RESQ	1
SYS_PCIBIOS_SERVICE_DIR:
	RESD	1
SYS_PCI_SERVICES:
	RESD	1

SECTION .note.GNU-stack noalloc noexec nowrite progbits
