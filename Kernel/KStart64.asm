%include "Kernel/KernelA.inc"

GLOBAL SYS_ENTER_LONG_MODE,CORE0_64BIT_INIT,KMain
EXTERN TaskInitFailed,KbdMsService
EXTERN SYS_RUN_LEVEL,MEM_PML4,KMainCpp,CPUStructInit,SET_GS_BASE,TaskInit,SET_FS_BASE

SECTION .boot64 progbits alloc exec nowrite align=16
BITS 32

SYS_ENTER_LONG_MODE:
	MOV	EAX,CR4
	OR	EAX,0xB0
	MOV	CR4,EAX
	MOV	EAX,[MEM_PML4]
	MOV	CR3,EAX

	MOV	ECX,0xC0000080
	XOR	EDX,EDX
	MOV	EAX,1<<8
	WRMSR
	MOV	EAX,CR0
	BTS	EAX,31
	MOV	CR0,EAX
	JMP	GDT_CS64:.segments

BITS 64
.segments:
	MOV	AX,GDT_DS
	MOV	DS,AX
	MOV	ES,AX
	MOV	SS,AX
	MOV	FS,AX
	MOV	GS,AX
	; The 32-bit caller pushes zero above its return address.
	RET

CORE0_64BIT_INIT:
	BTS	DWORD [REL SYS_RUN_LEVEL],RLf_64BIT
	FNINIT
	MOV	EAX,SYS_FIXED_AREA
	FXSAVE	[RAX]

	PUSH	SYS_FIXED_ADAM
	PUSH	SYS_FIXED_BOOT_CPU
	PUSH	0
	CALL	CPUStructInit
	CALL	SET_GS_BASE

	MOV	EDI,SYS_FIXED_ADAM_HC
	MOV	EAX,SYS_FIXED_CODE_BP
	MOV	[RDI+HC_BP],RAX
	MOV	DWORD [RDI+HC_SIGNATURE],'HcSV'
	LEA	RAX,[RDI+HC_NEXT_UM-8]
	MOV	[RDI+HC_NEXT_UM],RAX
	MOV	[RDI+HC_LAST_UM],RAX
	MOV	EAX,SYS_FIXED_ADAM
	MOV	[RDI+HC_MEM_TASK],RAX
	MOV	[RAX+CTask_CODE_HEAP],RDI
	MOV	[RAX+CTask_DATA_HEAP],RDI
	MOV	DWORD [RAX+CTask_SIGNATURE],'TskS'
	BTS	DWORD [REL SYS_RUN_LEVEL],RLf_16MEG_ADAM_HEAP_CTRL

	PUSH	MEM_ADAM_STK
	PUSH	SYS_FIXED_ADAM
	CALL	TaskInit
	TEST	RAX,RAX
	JZ	.failed
	CALL	SET_FS_BASE
	MOV	RSP,[RAX+CTask_RSP]

	JMP	KMain
.failed:
	CALL	TaskInitFailed

KMain:
	; Enter with Adam's saved RSP, then align for the C++ call.
	XOR	EBP,EBP
	AND	RSP,-16
	CALL	KMainCpp
.halt:
	HLT
	CALL	KbdMsService
	JMP	.halt

SECTION .note.GNU-stack noalloc noexec nowrite progbits
