static uint8_t packet_buf[8], raw_buf[0x1000];
static int64_t scan_buf[0x1000];
static CFifoU8 packet_fifo{packet_buf, 7, 0, 0};
static CFifoU8 raw_fifo{raw_buf, 0xFFF, 0, 0};
static CFifoI64 scan_fifo{scan_buf, 0xFFF, 0, 0};
static bool ready;

static void KbdStageByte(uint8_t raw_byte);

bool KbdCmdSend(uint16_t port, uint8_t value)
{
  auto start = GetTSC();
  auto timeout = uint64_t(cnts.time_stamp_freq) / 8;
  do {
    if (!(InU8(KBD_CTRL) & 2)) {
      OutU8(port, value);
      return true;
    }
  } while (GetTSC() - start < timeout);
  return false;
}

bool KbdCmdRead(uint8_t &value, bool auxiliary)
{
  auto start = GetTSC();
  auto timeout = uint64_t(cnts.time_stamp_freq) / 8;
  do {
    auto status = InU8(KBD_CTRL);
    if (status & 1) {
      value = InU8(KBD_PORT);
      bool is_aux = status & 0x20;
      if (is_aux == auxiliary)
        return true;
      if (is_aux)
        MsHardStageByte(value);
      else
        KbdStageByte(value);
    }
  } while (GetTSC() - start < timeout);
  return false;
}

static void KbdStageByte(uint8_t raw_byte)
{
  auto now = GetTSC();
  auto &packet = *kbd.fifo;
  if (now - uint64_t(kbd.timestamp) > uint64_t(cnts.time_stamp_freq) / 8)
    packet.out_ptr = packet.in_ptr;
  kbd.timestamp = now;
  bool first = !FifoCnt(packet);
  FifoIns(packet, raw_byte);
  if (first && raw_byte == 0xE0)
    return;
  auto &raw = *kbd.fifo2;
  bool space = raw.mask - FifoCnt(raw) >= FifoCnt(packet);
  while (FifoRem(packet, raw_byte))
    if (space)
      FifoIns(raw, raw_byte);
}

static bool KbdKeyCmd(uint8_t value, bool report_ack = false)
{
  for (unsigned retry = 0; retry < 3 && KbdCmdSend(KBD_PORT, value); ++retry) {
    auto start = GetTSC();
    auto timeout = uint64_t(cnts.time_stamp_freq) / 8;
    uint8_t reply;
    while (GetTSC() - start < timeout && KbdCmdRead(reply)) {
      if (reply == 0xFA) {
        if (report_ack)
          KbdStageByte(reply);
        return true;
      }
      if (reply == 0xFE)
        break;
      KbdStageByte(reply);
    }
  }
  return false;
}

static void KbdLEDsSet(uint32_t sc, bool report_ack)
{
  uint8_t state = (sc >> 14) & 1;
  state |= (sc >> 12) & 2;
  state |= (sc >> 10) & 4;
  if (KbdKeyCmd(0xED, report_ack))
    KbdKeyCmd(state, report_ack);
}

extern "C" void KbdTypeMaticCpp(uint8_t delay)
{
  if (!ready)
    return;
  auto flags = GetRFlags();
  asm volatile("cli" : : : "memory");
  if (KbdKeyCmd(0xF3, true))
    KbdKeyCmd(delay, true);
  SetRFlags(flags);
}

extern "C" int64_t Char2ScanCodeCpp(int64_t ch, int64_t sc_flags)
{
  if (sc_flags) {
    const auto *table = NORMAL_KEY_SCAN_DECODE_TABLE;
    if ((sc_flags & SCF_CTRL) || ch < 26)
      table = CTRL_KEY_SCAN_DECODE_TABLE;
    else if (bool(sc_flags & SCF_CAPS) !=
             (bool(sc_flags & SCF_SHIFT) || ('A' <= ch && ch <= 'Z')))
      table = SHIFT_KEY_SCAN_DECODE_TABLE;
    for (int64_t i = 0; i < 0x50; ++i)
      if (table[i] == ch)
        return i | sc_flags;
    return sc_flags;
  }
  const uint8_t *tables[]{NORMAL_KEY_SCAN_DECODE_TABLE,
                          SHIFT_KEY_SCAN_DECODE_TABLE,
                          CTRL_KEY_SCAN_DECODE_TABLE};
  constexpr uint32_t flags[]{0, SCF_SHIFT, SCF_CTRL};
  for (unsigned t = 0; t < 3; ++t)
    for (int64_t i = 0; i < 0x50; ++i)
      if (tables[t][i] == ch)
        return i | flags[t];
  return 0;
}

extern "C" uint8_t ScanCode2CharCpp(int64_t sc)
{
  if (sc & SCF_E0_PREFIX)
    return 0;
  auto *table = NORMAL_KEY_SCAN_DECODE_TABLE;
  if (sc & SCF_CTRL)
    table = CTRL_KEY_SCAN_DECODE_TABLE;
  else if (bool(sc & SCF_SHIFT) != bool(sc & SCF_CAPS))
    table = SHIFT_KEY_SCAN_DECODE_TABLE;
  auto code = sc & 0x7F;
  return code < 0x50 ? table[code] : 0;
}

static uint64_t KbdBuildSC(uint8_t raw_byte, uint8_t &last_raw_byte,
                           uint64_t last_sc)
{
  if (raw_byte == 0xE0) {
    last_raw_byte = raw_byte;
    return last_sc & ~uint64_t{0x1FF};
  }
  uint32_t sc = (raw_byte & 0x7F) | ((raw_byte & 0x80) ? SCF_KEY_UP : 0);
  if (last_raw_byte == 0xE0)
    sc |= SCF_E0_PREFIX;
  last_raw_byte = raw_byte;

  auto sc_raw = sc;
  auto flags = uint32_t(last_sc) & ~0x1FFu;
  auto map = flags & SCF_NUM ? num_lock_map : scan_code_map;
  if (auto mapped = map[uint8_t(sc)])
    sc = (sc & ~0xFFu) | mapped;

  auto code = uint8_t(sc);
  auto new_key = SCF_NEW_KEY;
  bool set_leds = false;
  if (sc & SCF_KEY_UP) {
    switch (code) {
      case SC_SHIFT: flags &= ~SCF_SHIFT; break;
      case SC_CTRL: flags &= ~SCF_CTRL; break;
      case SC_ALT: flags &= ~SCF_ALT; break;
      case SC_DELETE: flags &= ~SCF_DELETE; break;
      case SC_INS: flags &= ~SCF_INS; break;
      case SC_CAPS: flags ^= SCF_CAPS; set_leds = true; break;
      case SC_NUM: flags ^= SCF_NUM; set_leds = true; break;
      case SC_SCROLL: flags ^= SCF_SCROLL; set_leds = true; break;
    }
  } else {
    switch (code) {
      case SC_SHIFT:
        if (flags & SCF_SHIFT)
          new_key = 0;
        flags |= SCF_SHIFT;
        break;
      case SC_CTRL:
        if (flags & SCF_CTRL)
          new_key = 0;
        flags |= SCF_CTRL;
        break;
      case SC_ALT:
        if (flags & SCF_ALT)
          new_key = 0;
        flags |= SCF_ALT;
        break;
      case SC_DELETE: flags |= SCF_DELETE; break;
      case SC_INS: flags |= SCF_INS; break;
    }
    if ((flags & (SCF_CTRL | SCF_ALT)) == (SCF_CTRL | SCF_ALT)) {
      auto ch = ScanCode2CharCpp(code);
      if (code == 1 || code == 0x0F || ('a' <= ch && ch <= 'z'))
        new_key = 0;
    }
  }
  flags |= new_key;
  if (set_leds)
    KbdLEDsSet(flags, true);
  return uint64_t(flags | sc) | (uint64_t(flags | sc_raw) << 32);
}

void Ps2PktRead()
{
  auto status = InU8(KBD_CTRL);
  if (status & 1) {
    auto raw_byte = InU8(KBD_PORT);
    if (status & 0x20)
      MsHardStageByte(raw_byte);
    else
      KbdStageByte(raw_byte);
  }
}

extern "C" void IRQKbd();
extern "C" void IRQKbdCpp()
{
  OutU8(0x20, 0x20);
  kbd.irqs_working = true;
  Ps2PktRead();
}

bool KbdInit()
{
  kbd.fifo = &packet_fifo;
  kbd.fifo2 = &raw_fifo;
  kbd.scan_code_fifo = &scan_fifo;
  auto flags = GetRFlags();
  asm volatile("cli" : : : "memory");
  uint8_t config;
  bool okay = KbdCmdSend(KBD_CTRL, 0xA7) && KbdCmdSend(KBD_CTRL, 0xAD);
  if (okay) {
    for (unsigned i = 0; i < 32 && (InU8(KBD_CTRL) & 1); ++i)
      InU8(KBD_PORT);
    okay = KbdCmdSend(KBD_CTRL, 0x20) && KbdCmdRead(config) &&
           KbdCmdSend(KBD_CTRL, 0x60) &&
           KbdCmdSend(KBD_PORT, (config | 0x41) & ~2) &&
           KbdCmdSend(KBD_CTRL, 0xAE) && KbdKeyCmd(0xF0) &&
           KbdKeyCmd(0x02) && KbdKeyCmd(0xF4);
  }
  if (okay) {
    KbdLEDsSet(0, false);
    IntEntrySet(I_KBD, IRQKbd);
    ready = true;
    OutU8(0x21, InU8(0x21) & ~2);
  }
  SetRFlags(flags);
  return okay;
}

static void KbdHndlr()
{
  static uint8_t last_raw_byte;
  uint8_t raw_byte;
  if (!FifoRem(*kbd.fifo2, raw_byte))
    return;
  auto sc = KbdBuildSC(raw_byte, last_raw_byte, kbd.scan_code);
  if (raw_byte == 0xE0 && FifoRem(*kbd.fifo2, raw_byte))
    sc = KbdBuildSC(raw_byte, last_raw_byte, sc);
  if (sc & SCF_NEW_KEY) {
    kbd.new_key_timestamp = kbd.timestamp;
    sc &= ~(uint64_t{SCF_NEW_KEY} | (uint64_t{SCF_NEW_KEY} << 32));
    FifoIns(*kbd.scan_code_fifo, int64_t(sc));
    ++kbd.cnt;
    unsigned code = uint8_t(sc), raw = uint8_t(sc >> 32);
    if (!(sc & SCF_KEY_UP)) {
      kbd.last_down_scan_code = sc;
      kbd.down_bitmap[code / 32] |= 1U << (code % 32);
      kbd.down_bitmap2[raw / 32] |= 1U << (raw % 32);
    } else {
      kbd.down_bitmap[code / 32] &= ~(1U << (code % 32));
      kbd.down_bitmap2[raw / 32] &= ~(1U << (raw % 32));
    }
  }
  kbd.scan_code = sc;
}

static void KbdMsgsQue()
{
  if (auto *focus = sys_focus_task) {
    int64_t sc;
    while (FifoRem(*kbd.scan_code_fifo, sc))
      TaskMsgCpp(focus, nullptr, sc & SCF_KEY_UP ? MSG_KEY_UP : MSG_KEY_DOWN,
                 ScanCode2CharCpp(sc), sc, 0);
  }
}

extern "C" void KbdMsService()
{
  if (!kbd.fifo2)
    return;
  auto flags = GetRFlags();
  asm volatile("cli" : : : "memory");
  while (FifoCnt(*kbd.fifo2))
    KbdHndlr();
  KbdMsgsQue();
  MsHardHndlr();
  WinMsUpdate();
  WinQueIPMsgs(true);
  SetRFlags(flags);
}

void KbdPoll()
{
  auto flags = GetRFlags();
  asm volatile("cli" : : : "memory");
  if (ready || ms_hard.installed)
    while (InU8(KBD_CTRL) & 1)
      Ps2PktRead();
  KbdMsService();
  SetRFlags(flags);
}
