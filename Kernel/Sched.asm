%include "Kernel/KernelA.inc"

GLOBAL TASK_CONTEXT_SAVE,TASK_CONTEXT_RESTORE,RESTORE_SETH_TASK_IF_READY
GLOBAL _YIELD,_TASK_END_NOW,Exit,SYS_IDLE_PT
EXTERN SET_FS_BASE,TaskEnd,TaskKillDying,SysHlt,cnts,sys_semas

SECTION .text
BITS 64

TASK_CONTEXT_SAVE:
	PUSH	RSI
	PUSHFQ
	MOV	RSI,[FS:0]
	POP	QWORD [RSI+CTask_RFLAGS]
	POP	QWORD [RSI+CTask_RSI]
	MOV	[RSI+CTask_RAX],RAX

	MOV	RAX,RSP
	LEA	RSP,[RSI+CTask_R15+8]
	PUSH	R15
	PUSH	R14
	PUSH	R13
	PUSH	R12
	PUSH	R11
	PUSH	R10
	PUSH	R9
	PUSH	R8
	PUSH	RDI
	PUSH	RBP
	PUSH	RBX
	PUSH	RDX
	PUSH	RCX
	MOV	RSP,RAX

	MOV	RAX,[RSI+CTask_FPU]
	FXSAVE	[RAX]
	RET

TASK_CONTEXT_RESTORE:
	INC	QWORD [GS:CCPU_SWAP_CNT]
	BT	DWORD [RSI+CTask_RFLAGS],9
	JNC	.flags
	BTS	DWORD [GS:CCPU_FLAGS],0
.flags:
	INC	QWORD [RSI+CTask_SWAP_CNT]
	MOV	RAX,[RSI+CTask_FPU]
	FXRSTOR	[RAX]

	MOV	RAX,RSP
	LEA	RSP,[RSI+CTask_RCX]
	POP	RCX
	POP	RDX
	POP	RBX
	POP	RBP
	POP	RDI
	POP	R8
	POP	R9
	POP	R10
	POP	R11
	POP	R12
	POP	R13
	POP	R14
	POP	R15
	MOV	RSP,RAX

	MOV	RAX,[RSI+CTask_RAX]
	PUSH	GDT_DS
	PUSH	QWORD [RSI+CTask_RSP]
	PUSH	QWORD [RSI+CTask_RFLAGS]
	PUSH	GDT_CS64
	PUSH	QWORD [RSI+CTask_RIP]
	MOV	RSI,[RSI+CTask_RSI]
	IRETQ

END_RSI_TASK:
	MOV	RAX,RSI
	CALL	SET_FS_BASE
_TASK_END_NOW:
	CLD
	MOV	RBX,RSP
	AND	RSP,-16
	CALL	TaskEnd
	MOV	RSP,RBX
	MOV	RSI,RAX
	JMP	RESTORE_RSI_TASK

Exit:
	PUSHFQ
	CLI
	CALL	TASK_CONTEXT_SAVE
	CMP	RSI,[GS:CCPU_SETH_TASK]
	JE	SysHlt
	LEA	RAX,[REL Exit]
	MOV	[RSI+CTask_RIP],RAX
	POP	QWORD [RSI+CTask_RFLAGS]
	MOV	[RSI+CTask_RSP],RSP
	BTS	DWORD [RSI+CTask_FLAGS],TASKf_KILL_TASK
	TEST	BYTE [REL sys_semas+SEMA_DBG_MODE*DFT_CACHE_LINE_WIDTH],1
	JNZ	_TASK_END_NOW
	LOCK BTR QWORD [REL sys_semas+SEMA_SINGLE_USER*DFT_CACHE_LINE_WIDTH],0
	JMP	_TASK_END_NOW

_YIELD:
	PUSHFQ
	TEST	BYTE [REL sys_semas+SEMA_SINGLE_USER*DFT_CACHE_LINE_WIDTH],1
	JZ	.save
	POPFQ
	RET
.save:
	CLI
	CALL	TASK_CONTEXT_SAVE
	LEA	RAX,[REL .ret]
	MOV	[RSI+CTask_RIP],RAX
	POP	QWORD [RSI+CTask_RFLAGS]
	MOV	[RSI+CTask_RSP],RSP
	MOV	RBP,RSI
	MOV	RBX,RSP
	AND	RSP,-16
	CLD
	CALL	TaskKillDying
	MOV	RSP,RBX
	MOV	RSI,[RBP+CTask_NEXT_TASK]
	JMP	RESTORE_RSI_TASK
.ret:
	RET

RESTORE_RSI_TASK:
	BT	DWORD [RSI+CTask_FLAGS],TASKf_KILL_TASK
	JC	END_RSI_TASK
	TEST	DWORD [RSI+CTask_FLAGS],(1<<TASKf_AWAITING_MSG)|(1<<TASKf_SUSPENDED)
	JNZ	.next
	MOV	RAX,[REL cnts]
	CMP	[RSI+CTask_WAKE_JIFFY],RAX
	JG	.next
	MOV	RAX,RSI
	CALL	SET_FS_BASE
	JMP	TASK_CONTEXT_RESTORE

.next:
	MOV	RSI,[RSI+CTask_NEXT_TASK]
	CMP	RSI,[GS:CCPU_SETH_TASK]
	JNE	RESTORE_RSI_TASK
	BTR	DWORD [GS:CCPU_FLAGS],0
	JC	RESTORE_RSI_TASK
	MOV	RAX,[GS:CCPU_IDLE_TASK]
	MOV	RSP,[RAX+CTask_STK]
	ADD	RSP,[RSP+CTaskStk_SIZE]
	ADD	RSP,CTaskStk_BASE
	CALL	SET_FS_BASE
	STI
	HLT
SYS_IDLE_PT:
	CLI

RESTORE_SETH_TASK_IF_READY:
	MOV	RSI,[GS:CCPU_SETH_TASK]
	JMP	RESTORE_RSI_TASK

SECTION .note.GNU-stack noalloc noexec nowrite progbits
