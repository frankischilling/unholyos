%include "Kernel/KernelA.inc"

GLOBAL TASK_CONTEXT_SAVE,TASK_CONTEXT_RESTORE

SECTION .text
BITS 64

TASK_CONTEXT_SAVE:
	PUSH	RSI
	PUSHFQ
	MOV	RSI,[FS:0]
	POP	QWORD [RSI+CTask_RFLAGS]
	POP	QWORD [RSI+CTask_RSI]
	MOV	[RSI+CTask_RAX],RAX

	MOV	RAX,RSP
	LEA	RSP,[RSI+CTask_R15+8]
	PUSH	R15
	PUSH	R14
	PUSH	R13
	PUSH	R12
	PUSH	R11
	PUSH	R10
	PUSH	R9
	PUSH	R8
	PUSH	RDI
	PUSH	RBP
	PUSH	RBX
	PUSH	RDX
	PUSH	RCX
	MOV	RSP,RAX

	MOV	RAX,[RSI+CTask_FPU]
	FXSAVE	[RAX]
	RET

TASK_CONTEXT_RESTORE:
	INC	QWORD [GS:CCPU_SWAP_CNT]
	BT	DWORD [RSI+CTask_RFLAGS],9
	JNC	.flags
	BTS	DWORD [GS:CCPU_FLAGS],0
.flags:
	INC	QWORD [RSI+CTask_SWAP_CNT]
	MOV	RAX,[RSI+CTask_FPU]
	FXRSTOR	[RAX]

	MOV	RAX,RSP
	LEA	RSP,[RSI+CTask_RCX]
	POP	RCX
	POP	RDX
	POP	RBX
	POP	RBP
	POP	RDI
	POP	R8
	POP	R9
	POP	R10
	POP	R11
	POP	R12
	POP	R13
	POP	R14
	POP	R15
	MOV	RSP,RAX

	MOV	RAX,[RSI+CTask_RAX]
	PUSH	GDT_DS
	PUSH	QWORD [RSI+CTask_RSP]
	PUSH	QWORD [RSI+CTask_RFLAGS]
	PUSH	GDT_CS64
	PUSH	QWORD [RSI+CTask_RIP]
	MOV	RSI,[RSI+CTask_RSI]
	IRETQ

SECTION .note.GNU-stack noalloc noexec nowrite progbits
