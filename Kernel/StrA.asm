BITS 64
SECTION .text
GLOBAL PUT_HEX_U64,PUT_HEX_U32,PUT_HEX_U16,PUT_HEX_U8,PUT_CHARS,PUT_STR
GLOBAL _STRMATCH,StrMatchCpp
EXTERN PutHexHC,PutCharsHC,PutSHC

%macro PUSH_C_REGS 0
	PUSH	RAX
	PUSH	RCX
	PUSH	RDX
	PUSH	RBX
	PUSH	R8
	PUSH	R9
%endmacro

%macro POP_C_REGS 0
	POP	R9
	POP	R8
	POP	RBX
	POP	RDX
	POP	RCX
	POP	RAX
%endmacro

%macro PUT_HEX 2
%1:
	PUSH_C_REGS
	PUSH	%2
	PUSH	RAX
	CALL	PutHexHC
	POP_C_REGS
	RET
%endmacro

PUT_HEX PUT_HEX_U64,16
PUT_HEX PUT_HEX_U32,8
PUT_HEX PUT_HEX_U16,4
PUT_HEX PUT_HEX_U8,2

PUT_CHARS:
	PUSH_C_REGS
	PUSH	RAX
	CALL	PutCharsHC
	POP_C_REGS
	RET

PUT_STR:
	PUSH_C_REGS
	PUSH	RSI
	CALL	PutSHC
	POP_C_REGS
	RET

; Map SysV arguments to the reference HolyC stack entry point.
StrMatchCpp:
		PUSH	RSI
		PUSH	RDI
		CALL	_STRMATCH
		RET

_STRMATCH:
		PUSH	RBP
		MOV	RBP,RSP
		PUSH	RSI
		PUSH	RDI
		MOV	RSI,[RBP+24]
		TEST	RSI,RSI
		JZ	.L25
		MOV	RDI,[RBP+16]
		TEST	RDI,RDI
		JZ	.L25
		MOV	DL,[RDI]
		TEST	DL,DL
		JZ	.L20
		JMP	.L10
.L05:		INC	RSI
.L10:		LODSB
		TEST	AL,AL
		JZ	.L25
		CMP	AL,DL
		JNE	.L10
		DEC	RSI
		MOV	RCX,1
.L15:		MOV	AL,[RDI+RCX]
		TEST	AL,AL
		JZ	.L20
		CMP	AL,[RSI+RCX]
		JNE	.L05
		INC	RCX
		JMP	.L15
		DEC	RSI
.L20:		MOV	RAX,RSI
		JMP	.L30
.L25:		XOR	RAX,RAX
.L30:		POP	RDI
		POP	RSI
		POP	RBP
		RET	16

SECTION .note.GNU-stack noalloc noexec nowrite progbits
