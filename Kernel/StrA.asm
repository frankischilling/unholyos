BITS 64
SECTION .text
GLOBAL PUT_HEX_U64,PUT_HEX_U32,PUT_HEX_U16,PUT_HEX_U8,PUT_CHARS,PUT_STR
EXTERN PutHexHC,PutCharsHC,PutSHC

%macro PUSH_C_REGS 0
	PUSH	RAX
	PUSH	RBX
	PUSH	RCX
	PUSH	RDX
	PUSH	R8
	PUSH	R9
%endmacro

%macro POP_C_REGS 0
	POP	R9
	POP	R8
	POP	RDX
	POP	RCX
	POP	RBX
	POP	RAX
%endmacro

%macro PUT_HEX 2
%1:
	PUSH_C_REGS
	PUSH	%2
	PUSH	RAX
	CALL	PutHexHC
	POP_C_REGS
	RET
%endmacro

PUT_HEX PUT_HEX_U64,16
PUT_HEX PUT_HEX_U32,8
PUT_HEX PUT_HEX_U16,4
PUT_HEX PUT_HEX_U8,2

PUT_CHARS:
	PUSH_C_REGS
	PUSH	RAX
	CALL	PutCharsHC
	POP_C_REGS
	RET

PUT_STR:
	PUSH_C_REGS
	PUSH	RSI
	CALL	PutSHC
	POP_C_REGS
	RET

SECTION .note.GNU-stack noalloc noexec nowrite progbits
