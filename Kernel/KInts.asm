GLOBAL IntNop,IntWake,IRQ_TIMER,INT_FAULT,IntDivZero,IntMPCrash,SysHlt
EXTERN dev,IntCore0TimerHndlr,BootFault,TASK_CONTEXT_SAVE,TASK_CONTEXT_RESTORE
EXTERN RESTORE_SETH_TASK_IF_READY,IRQKbdCpp,IRQMsHardCpp
GLOBAL IRQKbd,IRQMsHard

%include "Kernel/KernelA.inc"

%define DEV_UNCACHED_ALIAS 0x10
%define LAPIC_EOI 0xFEE000B0

SECTION .text
BITS 64

IntNop:
	PUSH	RAX
	MOV	AL,0x20
	OUT	0xA0,AL
	OUT	0x20,AL
	POP	RAX
IntWake:
	PUSH	RAX
	PUSH	RDX
	MOV	RAX,[REL dev+DEV_UNCACHED_ALIAS]
	MOV	EDX,LAPIC_EOI
	MOV	DWORD [RAX+RDX],0
	POP	RDX
	POP	RAX
	IRETQ

IRQ_TIMER:
	CALL	TASK_CONTEXT_SAVE
	CLD
	MOV	RAX,[RSP]
	MOV	[RSI+CTask_RIP],RAX
	MOV	RAX,[RSP+16]
	MOV	[RSI+CTask_RFLAGS],RAX
	MOV	RAX,[RSP+24]
	MOV	[RSI+CTask_RSP],RAX

	LOCK INC QWORD [GS:CCPU_TOTAL_JIFFIES]
	BT	DWORD [RSI+CTask_FLAGS],TASKf_IDLE
	JNC	.tick
	LOCK INC QWORD [GS:CCPU_IDLE_PT_HITS]
.tick:
	MOV	RBX,RSP
	MOV	RBP,RSI
	AND	RSP,-16
	CALL	IntCore0TimerHndlr
	MOV	RSP,RBX
	MOV	RSI,RBP
	CMP	RSI,[GS:CCPU_IDLE_TASK]
	JE	RESTORE_SETH_TASK_IF_READY
	JMP	TASK_CONTEXT_RESTORE

%macro IRQ_PS2 2
%1:
	PUSH	RAX
	PUSH	RCX
	PUSH	RDX
	PUSH	RSI
	PUSH	RDI
	PUSH	R8
	PUSH	R9
	PUSH	R10
	PUSH	R11
	PUSH	RBX
	MOV	RBX,RSP
	AND	RSP,-16
	CLD
	CALL	%2
	MOV	RSP,RBX
	POP	RBX
	POP	R11
	POP	R10
	POP	R9
	POP	R8
	POP	RDI
	POP	RSI
	POP	RDX
	POP	RCX
	POP	RAX
	IRETQ
%endmacro

IRQ_PS2 IRQKbd,IRQKbdCpp
IRQ_PS2 IRQMsHard,IRQMsHardCpp

IntDivZero:
	PUSH	BYTE 0
	JMP	INT_FAULT

IntMPCrash:
	PUSH	BYTE 0x30
INT_FAULT:
	PUSH	RAX
	PUSH	RSI
	MOV	RSI,[FS:0]
	MOVZX	EAX,BYTE [RSP+16]
	MOV	[RSI+CTask_FAULT_NUM],RAX
	POP	RSI
	POP	RAX
	ADD	RSP,8

	CALL	TASK_CONTEXT_SAVE
	CLD
	MOV	EDI,[RSI+CTask_FAULT_NUM]
	XOR	EDX,EDX
	BT	QWORD [REL INT_FAULT_ERR_CODE_BITMAP],RDI
	JNC	.frame
	POP	RDX
.frame:
	MOV	[RSI+CTask_FAULT_ERR_CODE],RDX
	MOV	RAX,[RSP]
	MOV	[RSI+CTask_RIP],RAX
	MOV	RAX,[RSP+16]
	MOV	[RSI+CTask_RFLAGS],RAX
	MOV	RAX,[RSP+24]
	MOV	[RSI+CTask_RSP],RAX

	MOV	RDI,RSI
	AND	RSP,-16
	CALL	BootFault

SysHlt:
	CLI
.halt:
	HLT
	JMP	.halt

SECTION .rodata
ALIGN 8
INT_FAULT_ERR_CODE_BITMAP:
	DQ	0x00027D00,0,0,0

SECTION .note.GNU-stack noalloc noexec nowrite progbits
