%include "Kernel/KernelA.inc"
%include "Kernel/KCfg.inc"

GLOBAL SYS_KERNEL,SYS_BOOT_SRC,SYS_BOOT_BLK,SYS_RUN_LEVEL,MEM_BOOT_BASE
GLOBAL MEM_E801,MEM_E820,MEM_PHYSICAL_SPACE,SYS_PCI_BUSES
GLOBAL SYS_FONT_ADDRESS,SYS_E820_COUNT
GLOBAL SYS_COMPILE_TIME
EXTERN CORE0_32BIT_INIT,__core0_32bit_offset
EXTERN __patch_table_offset,__kernel_file_size

SECTION .boot16 progbits alloc exec nowrite align=16
BITS 16

	; CBinFile, followed by the CKernel fields used during startup.
	JMP	SHORT SYS_KERNEL
	DB	7,0
	DB	"TOSB"
	DQ	SYS_KERNEL_BASE
	DQ	__patch_table_offset
	DQ	__kernel_file_size

SYS_KERNEL:
	JMP	NEAR CORE0_16BIT_INIT
	ALIGN	4,DB 0x90
SYS_BOOT_SRC:		DD 0
SYS_BOOT_BLK:		DD 0
SYS_BOOT_PATCH_TABLE_BASE: DD 0
SYS_RUN_LEVEL:		DD 0
SYS_COMPILE_TIME:	DQ 0xB492000000000
MEM_BOOT_BASE:		DD 0
MEM_E801:		DW 0,0
MEM_E820:		TIMES MEM_E820_ENTRIES_NUM*MEM_E820_SIZE DB 0
MEM_PHYSICAL_SPACE:	DQ 0
SYS_GDT_PTR:		DW SYS_GDT_END-SYS_GDT-1
			DQ SYS_GDT
SYS_PCI_BUSES:		DW 256

	ALIGN	16,DB 0x90
SYS_GDT:
	DQ	0,0
	DQ	0x00CF92000000FFFF+(SYS_KERNEL_BASE<<16),0
	DQ	0x00CF9A000000FFFF+(SYS_KERNEL_BASE<<16),0
	DQ	0x00CF9A000000FFFF,0
	DQ	0x00209A0000000000,0
	DQ	0x0020FA0000000000,0
	DQ	0x00CF92000000FFFF,0
	DQ	0x00CFF2000000FFFF,0
	TIMES MP_PROCESSORS_NUM*2 DQ 0,0
SYS_GDT_END:

%if SYS_GDT_END-$$ != 5280
	%error CKernel layout differs from the boot header
%endif

CORE0_16BIT_INIT:
	CLI
	MOV	CX,(BOOT_RAM_LIMIT-BOOT_STK_SIZE)>>4
	MOV	SS,CX
	MOV	SP,BOOT_STK_SIZE
	JMP	SYS_KERNEL_SEG:(.segment-SYS_KERNEL)
.segment:
	MOV	CX,CS
	MOV	DS,CX
	MOV	ES,CX
	CLD
	MOV	[SYS_BOOT_SRC-SYS_KERNEL],EAX
	MOV	[SYS_BOOT_BLK-SYS_KERNEL],EBX
	MOV	DWORD [SYS_RUN_LEVEL-SYS_KERNEL],1<<RLf_16BIT
	STI

%if !KCFG_TEXT_MODE
	MOV	AX,0x4F02
	MOV	BX,0x12
	INT	0x10
	CMP	AX,0x004F
	JNE	.memory
	BTS	DWORD [SYS_RUN_LEVEL-SYS_KERNEL],RLf_VGA

	; Save the BIOS font for the early screen.
	PUSH	ES
	PUSH	BP
	MOV	AX,0x1130
	MOV	BH,6
	INT	0x10
	MOV	AX,ES
	MOVZX	EAX,AX
	SHL	EAX,4
	MOVZX	EBP,BP
	ADD	EAX,EBP
	MOV	[SYS_FONT_ADDRESS-SYS_KERNEL],EAX
	POP	BP
	POP	ES
%endif

.memory:
	MOV	AX,0xE801
	INT	0x15
	JC	.e820
	MOV	[MEM_E801-SYS_KERNEL],CX
	MOV	[MEM_E801+2-SYS_KERNEL],DX

.e820:
	XOR	EBX,EBX
	MOV	AX,DS
	MOV	ES,AX
	MOV	DI,MEM_E820-SYS_KERNEL
.entry:
	MOV	EAX,0xE820
	MOV	ECX,MEM_E820_SIZE
	MOV	EDX,0x534D4150
	INT	0x15
	JC	.memory_limit
	CMP	EAX,0x534D4150
	JNE	.memory_limit
	CMP	ECX,MEM_E820_SIZE
	JB	.memory_limit
	INC	DWORD [SYS_E820_COUNT-SYS_KERNEL]
	CMP	DWORD [SYS_E820_COUNT-SYS_KERNEL],MEM_E820_ENTRIES_NUM-1
	JAE	.memory_limit
	TEST	EBX,EBX
	JZ	.memory_limit
	ADD	DI,MEM_E820_SIZE
	JMP	.entry

.memory_limit:
	MOVZX	EAX,WORD [MEM_E801+2-SYS_KERNEL]
	SHL	EAX,16
	XOR	EDX,EDX
	ADD	EAX,SYS_16MEG_AREA_LIMIT
	ADC	EDX,0
	MOV	SI,MEM_E820-SYS_KERNEL
.range:
	CMP	BYTE [SI+16],0
	JE	.save_limit
	MOV	EBX,[SI]
	MOV	ECX,[SI+4]
	ADD	EBX,[SI+8]
	ADC	ECX,[SI+12]
	JC	.next_range
	CMP	ECX,EDX
	JB	.next_range
	JA	.new_limit
	CMP	EBX,EAX
	JBE	.next_range
.new_limit:
	MOV	EAX,EBX
	MOV	EDX,ECX
.next_range:
	ADD	SI,MEM_E820_SIZE
	JMP	.range
.save_limit:
	MOV	[MEM_PHYSICAL_SPACE-SYS_KERNEL],EAX
	MOV	[MEM_PHYSICAL_SPACE+4-SYS_KERNEL],EDX

	XOR	DX,DX
	MOV	AX,0xB101
	INT	0x1A
	CMP	DX,0x4350
	JNE	.protected
	MOVZX	CX,CL
	INC	CX
	MOV	[SYS_PCI_BUSES-SYS_KERNEL],CX

.protected:
	CLI
	IN	AL,0x92
	AND	AL,0xFE
	OR	AL,2
	OUT	0x92,AL
	MOV	DWORD [MEM_BOOT_BASE-SYS_KERNEL],SYS_KERNEL_BASE
	MOV	DWORD [SYS_BOOT_PATCH_TABLE_BASE-SYS_KERNEL],BOOT_RAM_BASE+__patch_table_offset

	O32 LGDT [SYS_GDT_PTR-SYS_KERNEL]
	MOV	EAX,SYS_START_CR0
	MOV	CR0,EAX
	JMP	DWORD GDT_BOOT_CS:__core0_32bit_offset

SYS_FONT_ADDRESS:	DD 0
SYS_E820_COUNT:		DD 0

SECTION .note.GNU-stack noalloc noexec nowrite progbits
