SECTION .text
BITS 64

; The decimal table uses the x87 Pow10 sequence and stores binary64 bits.
Pow10Bits:
	PUSH	RDI
	SUB	RSP,16
	FILD	QWORD [RSP+16]
	FSTP	QWORD [RSP+16]

	FSTCW	WORD [RSP]
	MOV	AX,[RSP]
	MOV	[RSP+2],AX
	OR	AX,0x0C00
	MOV	[RSP],AX
	FLDCW	WORD [RSP]

	FLDL2T
	FLD	QWORD [RSP+16]
	FMULP	ST1,ST0
	FST	QWORD [RSP+16]
	FRNDINT
	FLD	QWORD [RSP+16]
	FSUBRP	ST1,ST0
	F2XM1
	FLD1
	FADDP	ST1,ST0
	FSTP	QWORD [RSP+8]
	FLD	QWORD [RSP+16]
	FLD	QWORD [RSP+8]
	FSCALE
	FSTP	QWORD [RSP+8]
	FFREE	ST0
	FINCSTP

	FLDCW	WORD [RSP+2]
	MOV	RAX,[RSP+8]
	ADD	RSP,24
	RET

%macro F64_BINOP 2
%1:
	PUSH	RDI
	PUSH	RSI
	FLD	QWORD [RSP+8]
	%2	QWORD [RSP]
	FSTP	QWORD [RSP]
	POP	RAX
	ADD	RSP,8
	RET
%endmacro

F64_BINOP F64MulBits,FMUL
F64_BINOP F64DivBits,FDIV
F64_BINOP F64AddBits,FADD
F64_BINOP F64SubBits,FSUB

; Follow CMP_TEMPLATES' floating-point modulo sequence.
F64RemBits:
  PUSH RDI
  PUSH RSI
  FLD QWORD [RSP]
  FLD QWORD [RSP+8]
.retry:
  FPREM
  FNSTSW AX
  TEST AX,0x400
  JNZ .retry
  FSTP QWORD [RSP]
  FFREE ST0
  FINCSTP
  POP RAX
  ADD RSP,8
  RET

%macro F64_UNOP 2
%1:
	PUSH	RDI
	FLD	QWORD [RSP]
	%2
	FSTP	QWORD [RSP]
	POP	RAX
	RET
%endmacro

F64_UNOP F64AbsBits,FABS
F64_UNOP F64SqrtBits,FSQRT
F64_UNOP F64SinBits,FSIN
F64_UNOP F64CosBits,FCOS

; Compare binary64 arguments without changing the x87 stack depth.
F64CompareBits:
		PUSH	RDI
		PUSH	RSI
		FLD	QWORD [RSP]
		FLD	QWORD [RSP+8]
		FCOMIP	ST0,ST1
		FSTP	ST0
		LEA	RSP,[RSP+16]
		JP	.unordered
		JA	.greater
		JB	.less
		XOR	EAX,EAX
		RET
.unordered:
		MOV	EAX,2
		RET
.greater:
		MOV	EAX,1
		RET
.less:
		MOV	RAX,-1
		RET

F64ArgBits:
	PUSH	RDI
	PUSH	RSI
	FLD	QWORD [RSP]
	FLD	QWORD [RSP+8]
.retry:
	FPATAN
	FSTSW	AX
	TEST	AX,0x400
	JNZ	.retry
	FSTP	QWORD [RSP]
	POP	RAX
	ADD	RSP,8
	RET

F64Log10Bits:
	PUSH	RDI
	FLDLG2
	FLD	QWORD [RSP]
	FYL2X
	FSTP	QWORD [RSP]
	POP	RAX
	RET

F64Log2Bits:
	PUSH	RDI
	FLD1
	FLD	QWORD [RSP]
	FYL2X
	FSTP	QWORD [RSP]
	POP	RAX
	RET

F64ToI64:
	PUSH	RDI
	SUB	RSP,8
	FSTCW	WORD [RSP]
	MOV	AX,[RSP]
	AND	AX,~0x0C00
	OR	AX,SI
	MOV	[RSP+2],AX
	FLDCW	WORD [RSP+2]
	FLD	QWORD [RSP+8]
	FISTP	QWORD [RSP+8]
	FLDCW	WORD [RSP]
	MOV	RAX,[RSP+8]
	ADD	RSP,16
	RET

F64FromI64:
	PUSH	RDI
	FILD	QWORD [RSP]
	FSTP	QWORD [RSP]
	POP	RAX
	RET

I64MulF64Bits:
	PUSH	RDI
	PUSH	RSI
	FILD	QWORD [RSP+8]
	FMUL	QWORD [RSP]
	FSTP	QWORD [RSP]
	POP	RAX
	ADD	RSP,8
	RET

; Reference register ABI: RAX = RDX raised to RAX. Preserve the
; caller's RDI and RSI when entering the existing SysV implementation.
SYS_POW:
  PUSH RDI
  PUSH RSI
  MOV RDI,RDX
  MOV RSI,RAX
  CALL F64PowerBits
  POP RSI
  POP RDI
  RET

F64PowerBits:
	TEST	RSI,RSI
	JNZ	.again
	MOV	RAX,0x3FF0000000000000
	RET
.again:	TEST	RDI,RDI
	JNZ	.power
	XOR	EAX,EAX
	RET
.power:
	SUB	RSP,24
	MOV	[RSP],RDI
	MOV	[RSP+8],RSI
	FSTCW	WORD [RSP+16]
	MOV	AX,[RSP+16]
	OR	AX,0x0C00
	MOV	[RSP+18],AX
	FLDCW	WORD [RSP+18]
	FLD	QWORD [RSP+8]
	FLD	QWORD [RSP]
	FABS
	FYL2X
	FST	QWORD [RSP]
	FRNDINT
	FLD	QWORD [RSP]
	FSUBRP	ST1,ST0
	F2XM1
	FLD1
	FADDP	ST1,ST0
	FSTP	QWORD [RSP+8]
	FLD	QWORD [RSP]
	FLD	QWORD [RSP+8]
	FSCALE
	TEST	RDI,RDI
	JNS	.result
	MOV	[RSP+8],RSI
	FLD	QWORD [RSP+8]
	FISTTP	QWORD [RSP+8]
	TEST	BYTE [RSP+8],1
	JZ	.result
	FCHS
.result:
	FSTP	QWORD [RSP]
	FFREE	ST0
	FINCSTP
	FLDCW	WORD [RSP+16]
	MOV	RAX,[RSP]
	ADD	RSP,24
	RET

; HolyC stack-call entries from Terry A. Davis's public-domain KMathA.HC.
; Floating-point results are returned as binary64 bits in RAX.
_SIGN:
	FLD	QWORD [RSP+8]
	FTST
	FSTSW	AX
	FFREE	ST0
	FINCSTP
	MOV	DX,AX
	XOR	EAX,EAX
	BT	DX,14
	JC	.done
	MOV	RAX,0x3FF0000000000000
	BT	DX,8
	JNC	.done
	MOV	RAX,0xBFF0000000000000
.done:
	RET	8

%macro F64_ROUND 2
%1:
	SUB	RSP,8
	FSTCW	WORD [RSP]
	MOV	AX,[RSP]
	AND	AX,~0x0C00
	OR	AX,%2
	MOV	[RSP+2],AX
	FLDCW	WORD [RSP+2]
	FLD	QWORD [RSP+16]
	FRNDINT
	FSTP	QWORD [RSP+16]
	MOV	RAX,[RSP+16]
	FLDCW	WORD [RSP]
	ADD	RSP,8
	RET	8
%endmacro

F64_ROUND _ROUND,0
F64_ROUND _TRUNC,0x0C00
F64_ROUND _FLOOR,0x0400
F64_ROUND _CEIL,0x0800

_POW:
	MOV	RDX,[RSP+8]
	MOV	RAX,[RSP+16]
	CALL	SYS_POW
	RET	16

; Preserve the reference's truncating control word and intermediate
; binary64 stores instead of substituting a host libm operation.
%macro F64_EXP 2
%1:
	SUB	RSP,16
	FSTCW	WORD [RSP]
	MOV	AX,[RSP]
	OR	AX,0x0C00
	MOV	[RSP+2],AX
	FLDCW	WORD [RSP+2]
	%2
	FLD	QWORD [RSP+24]
	FMULP	ST1,ST0
	FST	QWORD [RSP+24]
	FRNDINT
	FLD	QWORD [RSP+24]
	FSUBRP	ST1,ST0
	F2XM1
	FLD1
	FADDP	ST1,ST0
	FSTP	QWORD [RSP+8]
	FLD	QWORD [RSP+24]
	FLD	QWORD [RSP+8]
	FSCALE
	FSTP	QWORD [RSP+8]
	FFREE	ST0
	FINCSTP
	FLDCW	WORD [RSP]
	MOV	RAX,[RSP+8]
	ADD	RSP,16
	RET	8
%endmacro

F64_EXP _POW10,FLDL2T
F64_EXP _EXP,FLDL2E

%macro F64_LOG 2
%1:
	%2
	FLD	QWORD [RSP+8]
	FYL2X
	FSTP	QWORD [RSP+8]
	MOV	RAX,[RSP+8]
	RET	8
%endmacro

F64_LOG _LOG10,FLDLG2
F64_LOG _LOG2,FLD1
F64_LOG _LN,FLDLN2

_FLDCW:
	FLDCW	WORD [RSP+8]
	RET	8
_FSTCW:
	SUB	RSP,8
	FSTCW	WORD [RSP]
	MOVZX	EAX,WORD [RSP]
	ADD	RSP,8
	RET
