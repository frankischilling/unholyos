GLOBAL Pow10Bits
GLOBAL F64MulBits,F64DivBits,F64AddBits,F64Log10Bits,F64Log2Bits,F64ToI64,F64FromI64
GLOBAL I64MulF64Bits,F64SqrtBits
GLOBAL F64PowerBits

SECTION .text
BITS 64

; The decimal table uses the x87 Pow10 sequence and stores binary64 bits.
Pow10Bits:
	PUSH	RDI
	SUB	RSP,16
	FILD	QWORD [RSP+16]
	FSTP	QWORD [RSP+16]

	FSTCW	WORD [RSP]
	MOV	AX,[RSP]
	MOV	[RSP+2],AX
	OR	AX,0x0C00
	MOV	[RSP],AX
	FLDCW	WORD [RSP]

	FLDL2T
	FLD	QWORD [RSP+16]
	FMULP	ST1,ST0
	FST	QWORD [RSP+16]
	FRNDINT
	FLD	QWORD [RSP+16]
	FSUBRP	ST1,ST0
	F2XM1
	FLD1
	FADDP	ST1,ST0
	FSTP	QWORD [RSP+8]
	FLD	QWORD [RSP+16]
	FLD	QWORD [RSP+8]
	FSCALE
	FSTP	QWORD [RSP+8]
	FFREE	ST0
	FINCSTP

	FLDCW	WORD [RSP+2]
	MOV	RAX,[RSP+8]
	ADD	RSP,24
	RET

%macro F64_BINOP 2
%1:
	PUSH	RDI
	PUSH	RSI
	FLD	QWORD [RSP+8]
	%2	QWORD [RSP]
	FSTP	QWORD [RSP]
	POP	RAX
	ADD	RSP,8
	RET
%endmacro

F64_BINOP F64MulBits,FMUL
F64_BINOP F64DivBits,FDIV
F64_BINOP F64AddBits,FADD

F64SqrtBits:
	PUSH	RDI
	FLD	QWORD [RSP]
	FSQRT
	FSTP	QWORD [RSP]
	POP	RAX
	RET

F64Log10Bits:
	PUSH	RDI
	FLDLG2
	FLD	QWORD [RSP]
	FYL2X
	FSTP	QWORD [RSP]
	POP	RAX
	RET

F64Log2Bits:
	PUSH	RDI
	FLD1
	FLD	QWORD [RSP]
	FYL2X
	FSTP	QWORD [RSP]
	POP	RAX
	RET

F64ToI64:
	PUSH	RDI
	SUB	RSP,8
	FSTCW	WORD [RSP]
	MOV	AX,[RSP]
	AND	AX,~0x0C00
	OR	AX,SI
	MOV	[RSP+2],AX
	FLDCW	WORD [RSP+2]
	FLD	QWORD [RSP+8]
	FISTP	QWORD [RSP+8]
	FLDCW	WORD [RSP]
	MOV	RAX,[RSP+8]
	ADD	RSP,16
	RET

F64FromI64:
	PUSH	RDI
	FILD	QWORD [RSP]
	FSTP	QWORD [RSP]
	POP	RAX
	RET

I64MulF64Bits:
	PUSH	RDI
	PUSH	RSI
	FILD	QWORD [RSP+8]
	FMUL	QWORD [RSP]
	FSTP	QWORD [RSP]
	POP	RAX
	ADD	RSP,8
	RET

F64PowerBits:
	TEST	RSI,RSI
	JNZ	.again
	MOV	RAX,0x3FF0000000000000
	RET
.again:	TEST	RDI,RDI
	JNZ	.power
	XOR	EAX,EAX
	RET
.power:
	SUB	RSP,24
	MOV	[RSP],RDI
	MOV	[RSP+8],RSI
	FSTCW	WORD [RSP+16]
	MOV	AX,[RSP+16]
	OR	AX,0x0C00
	MOV	[RSP+18],AX
	FLDCW	WORD [RSP+18]
	FLD	QWORD [RSP+8]
	FLD	QWORD [RSP]
	FABS
	FYL2X
	FST	QWORD [RSP]
	FRNDINT
	FLD	QWORD [RSP]
	FSUBRP	ST1,ST0
	F2XM1
	FLD1
	FADDP	ST1,ST0
	FSTP	QWORD [RSP+8]
	FLD	QWORD [RSP]
	FLD	QWORD [RSP+8]
	FSCALE
	TEST	RDI,RDI
	JNS	.result
	MOV	[RSP+8],RSI
	FLD	QWORD [RSP+8]
	FISTTP	QWORD [RSP+8]
	TEST	BYTE [RSP+8],1
	JZ	.result
	FCHS
.result:
	FSTP	QWORD [RSP]
	FFREE	ST0
	FINCSTP
	FLDCW	WORD [RSP+16]
	MOV	RAX,[RSP]
	ADD	RSP,24
	RET

SECTION .note.GNU-stack noalloc noexec nowrite progbits
